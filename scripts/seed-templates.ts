type BlockDef =
  | { type: "divider" }
  | { type: "callout"; text: string; icon?: string }
  | { type: string; text: string };

function snap(title: string, icon: string, blockDefs: BlockDef[]) {
  return {
    title,
    icon,
    cover_url: null,
    is_full_width: false,
    font_family: "default",
    blocks: blockDefs.map((b, i) => {
      let content: Record<string, unknown> | null = null;
      if (b.type === "divider") {
        content = {};
      } else if (b.type === "callout") {
        const calloutB = b as { type: "callout"; text: string; icon?: string };
        content = calloutB.text
          ? { icon: calloutB.icon ?? "💡", color: "", text: [{ text: calloutB.text, marks: [] }] }
          : null;
      } else {
        const textB = b as { type: string; text: string };
        content = textB.text ? { text: [{ text: textB.text, marks: [] }] } : null;
      }
      return {
        id: crypto.randomUUID(),
        type: b.type,
        content,
        schema_version: 1,
        order_index: i,
        parent_block_id: null,
        children: [],
      };
    }),
    subpages: [],
    database_schema: null,
  };
}

