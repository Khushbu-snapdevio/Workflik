async function main() {
  const [{ db }, { templates }, { eq }] = await Promise.all([
    import("@/lib/db"),
    import("@/lib/db/schema"),
    import("drizzle-orm"),
  ]);

  console.log("Deleting existing built-in templates…");
  await db.delete(templates).where(eq(templates.isBuiltIn, true));

  console.log("Seeding 19 built-in templates…");

  const rows = TEMPLATES.map((t) => ({
    name:         t.name,
    description:  t.description,
    category:     t.category,
    isBuiltIn:    true,
    status:       "published" as const,
    workspaceId:  null,
    createdBy:    null,
    pageSnapshot: snap(t.name, t.icon, t.blocks),
  }));

  await db.insert(templates).values(rows);
  console.log(`✓ Seeded ${rows.length} templates.`);
  process.exit(0);
}

main().catch((err) => {
  console.error("Failed:", err);
  process.exit(1);
});
